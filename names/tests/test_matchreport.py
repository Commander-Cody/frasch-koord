def test_the_report_has_a_section_for_every_state(world: Path) -> None:
    (world / "places.csv").write_text(places_text(EVERY_STATE), encoding="utf-8")
    rows = placelist.read(str(world / "places.csv"), REGISTRY).rows
    stamp = Stamp({"places.csv": "ce013625030ba8dba906f756967f9e9ca394464a"}, [])
    matchreport.write(rows, EVERY_STATE_RESULTS, str(world / "REPORT.md"), REGISTRY, stamp)
    assert (world / "REPORT.md").read_text(encoding="utf-8") == EVERY_STATE_REPORT + (
        '\n<!-- built_from: {"places.csv":"ce013625030ba8dba906f756967f9e9ca394464a",'
        '"extracts":[]} -->\n'
    )


STAMP = Stamp({"places.csv": "ce013625030ba8dba906f756967f9e9ca394464a"}, [])
AMBIGUOUS_ROW = {"id": "kaamp", "kind": "settlement", "solring": "Kaamp", "de": "Kampen"}


def report_of(world: Path, candidate: RankedCandidate) -> str:
    """The report of a list whose one row is ambiguous, with `candidate`."""
    (world / "places.csv").write_text(places_text([AMBIGUOUS_ROW]), encoding="utf-8")
    rows = placelist.read(str(world / "places.csv"), REGISTRY).rows
    results = {"kaamp": MatchResult(Outcome.AMBIGUOUS, candidates=(candidate,))}
    matchreport.write(rows, results, str(world / "REPORT.md"), REGISTRY, STAMP)
    return (world / "REPORT.md").read_text(encoding="utf-8")


def test_the_report_cuts_a_candidates_name_to_forty_characters(world: Path) -> None:
    long = ranked("n", 1, 8.9, 54.7, name="Kampen " + "x" * 40, place="hamlet")
    assert f"`n/1:Kampen {'x' * 33}:hamlet:0`" in report_of(world, long)


def test_the_report_says_when_a_candidate_has_no_position(world: Path) -> None:
    nowhere: RankedCandidate = {
        **cand("r", 1, None, None, name="Kampen", place="hamlet"),
        "rank": 0,
    }
    assert "`r/1:Kampen:hamlet:?`" in report_of(world, nowhere)


def test_the_report_replaces_the_last_one_in_one_step(world: Path) -> None:
    # never half written: the old file stays whole under its other name
    (world / "REPORT.md").write_text("# an older report\n", encoding="utf-8")
    os.link(world / "REPORT.md", world / "kept.md")
    report_of(world, ranked("n", 1, 8.9, 54.7, name="Kampen", place="hamlet"))
    assert (world / "kept.md").read_text(encoding="utf-8") == "# an older report\n"
